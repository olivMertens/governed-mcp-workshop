import { execFileSync } from "node:child_process";
import { isUtf8 } from "node:buffer";
import { lstatSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync, gunzipSync } from "node:zlib";

const root = fileURLToPath(new URL("../", import.meta.url));
const setup = "setup-workshop-mcp.ps1";

export function readScaffoldFiles(directory = root) {
    const entries = execFileSync("git", ["ls-files", "-v", "-z"], { cwd: directory, encoding: "utf8" })
        .split("\0").filter(Boolean).sort((a, b) => a.slice(2) < b.slice(2) ? -1 : a.slice(2) > b.slice(2) ? 1 : 0);
    const files = {};
    for (const entry of entries) {
        const name = entry.slice(2);
        if (name === setup) continue;
        if (/(^|\/)(?:\.workshop|\.azure|\.terraform)(\/|$)|\.tfstate(?:\.|$)|\.tfplan$|\.private\.json$/.test(name)) {
            throw new Error(`Private state must never be embedded: ${name}`);
        }
        const path = join(directory, name);
        if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink()) throw new Error(`Not a regular source file: ${name}`);
        // Local skip-worktree overrides (for example MCP settings) are never distributed.
        let bytes = /^[a-zS]/.test(entry)
            ? execFileSync("git", ["show", `HEAD:${name}`], { cwd: directory, maxBuffer: 32 * 1024 * 1024 })
            : readFileSync(path);
        if (isUtf8(bytes) && !bytes.includes(0)) bytes = Buffer.from(bytes.toString("utf8").replaceAll("\r\n", "\n"));
        files[name] = bytes.toString("base64");
    }
    return files;
}

export function scaffoldSection(files) {
    const payload = gzipSync(Buffer.from(JSON.stringify(files)), { level: 9 }).toString("base64");
    return `# --- 3. Embedded scaffold ------------------------------------------------------
# Generated by scripts/sync-scaffold.mjs. Do not edit the payload by hand.
Write-Step 'Writing the workshop scaffold'
$scaffoldGzip = '${payload}'
$inputStream = [IO.MemoryStream]::new([Convert]::FromBase64String($scaffoldGzip))
$gzipStream = [IO.Compression.GZipStream]::new($inputStream, [IO.Compression.CompressionMode]::Decompress)
$reader = [IO.StreamReader]::new($gzipStream, [Text.Encoding]::UTF8)
try { $snapshot = $reader.ReadToEnd() | ConvertFrom-Json -AsHashtable }
finally { $reader.Dispose(); $gzipStream.Dispose(); $inputStream.Dispose() }
foreach ($relative in $snapshot.Keys) {
    if ($relative -match '(^|/)\\.\\.?(/|$)|\\\\|:' -or [IO.Path]::IsPathRooted($relative)) {
        throw 'Invalid embedded file path; setup stopped.'
    }
    $target = Join-Path $Path ($relative.Replace('/', [IO.Path]::DirectorySeparatorChar))
    $null = New-Item -ItemType Directory -Path (Split-Path $target -Parent) -Force
    [IO.File]::WriteAllBytes($target, [Convert]::FromBase64String($snapshot[$relative]))
    Write-Host "   + $relative"
}
Copy-Item -LiteralPath $PSCommandPath -Destination (Join-Path $Path 'setup-workshop-mcp.ps1')

`;
}

export function synchronizeScaffold(directory = root, check = false) {
    const path = join(directory, setup);
    const source = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
    const start = source.indexOf("# --- 3. Embedded scaffold ");
    const end = source.indexOf("# --- 4. Git and GitHub ", start);
    if (start < 0 || end < 0) throw new Error("Scaffold section markers are missing.");
    const files = readScaffoldFiles(directory);
    const section = scaffoldSection(files);
    const updated = source.slice(0, start) + section + source.slice(end);
    if (check) {
        const actual = source.slice(start, end);
        const pattern = /\$scaffoldGzip = '([^']+)'/;
        const match = actual.match(pattern);
        if (!match || gunzipSync(Buffer.from(match[1], "base64")).toString("utf8") !== JSON.stringify(files) ||
            actual.replace(pattern, "PAYLOAD") !== section.replace(pattern, "PAYLOAD")) {
            throw new Error("Scaffold is stale. Run node scripts/sync-scaffold.mjs after source changes.");
        }
    }
    if (!check) writeFileSync(path, updated);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    synchronizeScaffold(root, process.argv.includes("--check"));
    console.log(process.argv.includes("--check") ? "PASS standalone scaffold matches all distributable tracked files." : "Updated standalone scaffold.");
}
